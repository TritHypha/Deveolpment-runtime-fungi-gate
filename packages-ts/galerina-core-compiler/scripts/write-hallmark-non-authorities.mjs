import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = resolve(HERE, "..");
const REPOSITORY_ROOT = resolve(PACKAGE_ROOT, "..", "..");
const SOURCE = resolve(PACKAGE_ROOT, "governance", "hallmark-non-authorities.json");
const DIST_OUTPUT = resolve(PACKAGE_ROOT, "dist", "hallmark-non-authorities.json");
const DOC_OUTPUT = resolve(REPOSITORY_ROOT, "docs", "generated", "HALLMARK-NON-AUTHORITIES.md");

const sourceText = await readFile(SOURCE, "utf8");
const registry = JSON.parse(sourceText);

if (registry.schemaId !== "galerina.hallmark.non-authorities.v1") {
  throw new Error("REFUSED: unknown Hallmark non-authority registry schema.");
}
if (!Array.isArray(registry.entries) || registry.entries.length === 0) {
  throw new Error("REFUSED: Hallmark non-authority registry is empty.");
}

const seen = new Set();
for (const entry of registry.entries) {
  if (typeof entry?.id !== "string" || !/^[a-z0-9.-]+$/.test(entry.id)) {
    throw new Error("REFUSED: malformed Hallmark non-authority identifier.");
  }
  if (seen.has(entry.id)) {
    throw new Error(`REFUSED: repeated Hallmark non-authority identifier '${entry.id}'.`);
  }
  if (typeof entry.description !== "string" || entry.description.trim() === "") {
    throw new Error(`REFUSED: missing description for '${entry.id}'.`);
  }
  seen.add(entry.id);
}

const canonicalJson = `${JSON.stringify(registry, null, 2)}\n`;
const rows = registry.entries.map(
  (entry) => `| \`${entry.id}\` | ${entry.description.replaceAll("|", "\\|")} |`,
);
const markdown = `# Hallmark non-authorities\n\n`+
  `> Generated from the compiler-owned Hallmark non-authority registry. Do not edit this file directly.\n\n`+
  `A Hallmark is typed evidence produced by its rejecting assay. It is never an authority token.\n\n`+
  `| Authority class | Binding exclusion |\n`+
  `|---|---|\n${rows.join("\n")}\n`;

await mkdir(dirname(DIST_OUTPUT), { recursive: true });
await mkdir(dirname(DOC_OUTPUT), { recursive: true });
await writeFile(DIST_OUTPUT, canonicalJson, "utf8");
await writeFile(DOC_OUTPUT, markdown, "utf8");
console.log(`Hallmark non-authorities: ${registry.entries.length} entries generated.`);
