/**
 * Derive every living-document output before any mutation.
 */
function deriveTargets() {
  const outputs = new Map();
  const failures = [];
  for (const rel of TARGETS) {
    const abs = join(ROOT, rel);
    if (!existsSync(abs)) {
      failures.push(`${rel} (file MISSING)`);
      continue;
    }
    const next = injectBlock(readFileSync(abs, "utf8"), block);
    if (next === null) {
      failures.push(`${rel} (SUBWAY markers missing, duplicated, or misordered)`);
      continue;
    }
    outputs.set(abs, next);
  }
  return { outputs, failures };
}

