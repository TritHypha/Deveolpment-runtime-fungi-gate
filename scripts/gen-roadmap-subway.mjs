  // DRIVEN control 2: an empty baseline is fail-closed, not a zero-station map.
  ok(throws(() => stageLine({ stages: {} }, led)), "★ DRIVEN: an empty stage baseline is fail-closed");
  // DRIVEN control 3: an EMPTY ledger must render zero authoritative — proving fill is read, not assumed.
  ok(stageLine(hb, { twins: [] }).every((s) => !s.authoritative), "★ DRIVEN: an empty authority ledger renders 0 solid stations");

  // DRIVEN control 4: the evidence classifier must actually discriminate — the whole point of the dashed ring.
  ok(evidenceClass({ evidence: { live: "x" } }) === "live", "evidence: live detected");
  ok(evidenceClass({ evidence: { ladder: ["A"] } }) === "ladder", "evidence: ladder detected");
  ok(evidenceClass({ evidence: { asserted: "x" } }) === "asserted", "evidence: asserted detected");
  ok(evidenceClass({ evidence: { ladder: [] } }) === "asserted", "★ DRIVEN: an EMPTY ladder is asserted, not measured (an empty set is not evidence)");

