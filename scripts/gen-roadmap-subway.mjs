//
// Why this exists: the README's "Where the project is" table was HAND-TYPED and had gone stale (it still
// described the RD-0528 authority cutover as entirely un-flipped after five stages had flipped). A status
// number that a human types is a claim; a status number a tool derives from the artifact that decides it is
// evidence. This tool derives EVERY position and EVERY station state from a live source, and — like
// gen-status-blocks.mjs — owns a marker-delimited region plus a `--check` drift gate so it cannot go stale
// again silently.
//
// It also makes the project's own honesty problem VISIBLE rather than buried in JSON: percent-audit rows
// carry an evidence class (live / ladder = measured, asserted = hand-typed debt). Measured stations are
// solid; asserted stations are hollow with a dashed ring. A map that is mostly hollow is telling the truth
// about itself.
//
//   node scripts/gen-roadmap-subway.mjs               # print the markdown block to stdout
//   node scripts/gen-roadmap-subway.mjs --write       # write the SVG + inject the block into the targets
//   node scripts/gen-roadmap-subway.mjs --check       # exit 1 if any target's block is stale (the gate)
//   node scripts/gen-roadmap-subway.mjs --self-test   # DRIVE the generator with synthetic bad inputs
