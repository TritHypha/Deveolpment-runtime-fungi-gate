function loadJSON(rel) {
  const abs = join(ROOT, rel);
  if (!existsSync(abs)) throw new Error(`source missing: ${rel} (fail-closed — a roadmap with an unreadable ledger is not a roadmap)`);
  return JSON.parse(readFileSync(abs, "utf8"));
}

// component-health --json is the single source for the percentage sections (same source gen-status-blocks uses).
function percentAudit() {
  const r = spawnSync(process.execPath, [join(ROOT, "scripts", "component-health.mjs"), "--json"],
    { cwd: ROOT, encoding: "utf8", windowsHide: true, maxBuffer: 32 * 1024 * 1024 });
  if (r.status !== 0) throw new Error(`component-health --json failed (exit ${r.status})`);
  return JSON.parse(r.stdout).percentAudit;
}

// The compiler pipeline ORDER is an authored fact (the stages run in this sequence); MEMBERSHIP is derived.
// The assertion below is what keeps the authored half honest: add or remove a stage in the ledger and this
// throws rather than quietly dropping a station off the map.
const PIPELINE_ORDER = Object.freeze([
  "lexer", "parser", "type-checker", "effect-checker", "gir-emitter", "governance-verifier", "runtime",
]);

export function stageLine(hashBaseline, ledger) {
  const known = Object.keys(hashBaseline?.stages ?? {});
  if (known.length === 0) throw new Error("stage-hash baseline lists no stages — fail-closed");
  const missing = known.filter((s) => !PIPELINE_ORDER.includes(s));
  const extra = PIPELINE_ORDER.filter((s) => !known.includes(s));
  if (missing.length || extra.length) {
    throw new Error(`PIPELINE_ORDER is out of sync with the stage ledger (unplaced: ${missing.join(",") || "none"} · phantom: ${extra.join(",") || "none"}) — fix the order list, do not render a partial map`);
  }
  // A stage is AUTHORITATIVE iff it has a ledger entry; the ledger names files, so strip the extension.
  const flipped = new Set((ledger?.twins ?? []).map((t) => String(t.file ?? "").replace(/\.fungi$/, "")));
  return PIPELINE_ORDER.map((name) => ({
    name,
    authoritative: flipped.has(name),
    // Every stage in the baseline is byte-pinned; that is the R3 evidence the flip ladder stands on.
    pinned: Boolean(hashBaseline.stages[name]?.sha256),
  }));
}

// Evidence class of a percent-audit row: measured (a live reading or a countable ladder) vs asserted (typed).
export function evidenceClass(row) {
  const e = row?.evidence;
  if (!e) return "none";                                     // a WORD row carries no number to evidence
  if (e.live) return "live";                                 // read from a live artifact every run
  if (Array.isArray(e.ladder) && e.ladder.length) return "ladder"; // derived from a countable set
  return "asserted";                                         // hand-typed debt — the class we are burning down
}

// --- the map -------------------------------------------------------------------------------------------
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// Palette: one hue per line, plus a neutral for the un-measured. Deliberately NOT the accent-on-dark cliche;
// these are transit-map inks on paper, which is the idiom the owner asked for.
const LINES = Object.freeze({
  selfhost: "#c8102e", // red line — compiler self-hosting (RD-0528)
  thesis: "#0f7b6c",   // green line — Zero-Trust thesis boundaries
  build: "#1c5ea8",    // blue line — build progress
  kernel: "#b8860b",   // amber line — kernel execution cutover (RD-0361)
});

function station(x, y, colour, filled, measured) {
  // Filled = reached/authoritative. Dashed ring = the number is ASSERTED, not measured — the map refuses to
  // let a hand-typed percentage look identical to a derived one.
  const dash = measured ? "" : ` stroke-dasharray="3 2.5"`;
  return `<circle cx="${x}" cy="${y}" r="6.5" fill="${filled ? colour : "var(--paper)"}" stroke="${colour}" stroke-width="2.75"${dash}/>`;
}

export function renderSVG({ stages, thesis, build, kernel, meta }) {
  const W = 1180, PAD_L = 220, PAD_R = 70, TRACK = W - PAD_L - PAD_R;
  const x = (pct) => PAD_L + (TRACK * pct) / 100;
  const out = [];
  let y = 96;

  const rowLabel = (text, sub) =>
    `<text x="${PAD_L - 18}" y="${y + 4}" text-anchor="end" class="stn">${esc(text)}</text>` +
    (sub ? `<text x="${PAD_L - 18}" y="${y + 18}" text-anchor="end" class="sub">${esc(sub)}</text>` : "");

  // --- Line 1: compiler self-hosting. An ORDINAL line — stations are stages in pipeline order, evenly
  // spaced, because "how far along the pipeline" is a sequence, not a percentage. Fill = authority flipped.
  out.push(`<text x="${PAD_L - 18}" y="${y - 34}" text-anchor="end" class="line-name" fill="${LINES.selfhost}">Self-hosting</text>`);
  out.push(`<text x="${PAD_L - 18}" y="${y - 20}" text-anchor="end" class="sub">RD-0528 · authority ladder</text>`);
  const sx = (i) => PAD_L + (TRACK * i) / (stages.length - 1);
  out.push(`<line x1="${sx(0)}" y1="${y}" x2="${sx(stages.length - 1)}" y2="${y}" stroke="${LINES.selfhost}" stroke-width="7" stroke-linecap="round" opacity="0.9"/>`);
  stages.forEach((s, i) => {
    out.push(station(sx(i), y, LINES.selfhost, s.authoritative, true)); // every stage is byte-pinned: measured
    out.push(`<text x="${sx(i)}" y="${y - 16}" text-anchor="middle" class="stn">${esc(s.name)}</text>`);
    out.push(`<text x="${sx(i)}" y="${y + 24}" text-anchor="middle" class="sub">${s.authoritative ? "authoritative" : "differential"}</text>`);
  });
  y += 74;

  // --- Line 4 rides here too: the kernel cutover is also ordinal (a count of flipped sentinels), so it gets
  // a short interchange stub rather than a full percentage track — it has no denominator in any ledger.
  out.push(`<text x="${PAD_L - 18}" y="${y + 4}" text-anchor="end" class="line-name" fill="${LINES.kernel}">Kernel cutover</text>`);
  out.push(`<text x="${PAD_L - 18}" y="${y + 18}" text-anchor="end" class="sub">RD-0361 · sentinel twins</text>`);
  const kx = (i) => PAD_L + 26 * i;
  out.push(`<line x1="${kx(0)}" y1="${y}" x2="${kx(Math.max(kernel.length - 1, 0))}" y2="${y}" stroke="${LINES.kernel}" stroke-width="7" stroke-linecap="round" opacity="0.9"/>`);
  kernel.forEach((_, i) => out.push(station(kx(i), y, LINES.kernel, true, true)));
  out.push(`<text x="${kx(Math.max(kernel.length - 1, 0)) + 22}" y="${y + 4}" class="sub">${kernel.length} authoritative in the ledger · the differential remainder has no ledger denominator (not counted here)</text>`);
  y += 76;

  // --- Percentage lines: x-position IS the number. A station's horizontal place cannot be prettified.
  const scaleY = y;
  out.push(`<line x1="${x(0)}" y1="${scaleY}" x2="${x(100)}" y2="${scaleY}" stroke="var(--rule)" stroke-width="1"/>`);
  for (let p = 0; p <= 100; p += 25) {
    out.push(`<line x1="${x(p)}" y1="${scaleY - 4}" x2="${x(p)}" y2="${scaleY + 4}" stroke="var(--rule)" stroke-width="1"/>`);
    out.push(`<text x="${x(p)}" y="${scaleY - 10}" text-anchor="middle" class="sub">${p}%</text>`);
  }
  y += 34;

  const pctLine = (title, sub, colour, rows) => {
    out.push(`<text x="${PAD_L - 18}" y="${y - 12}" text-anchor="end" class="line-name" fill="${colour}">${esc(title)}</text>`);
    out.push(`<text x="${PAD_L - 18}" y="${y + 2}" text-anchor="end" class="sub">${esc(sub)}</text>`);
    for (const r of rows) {
      y += 26;
      out.push(rowLabel(r.label));
      // The track runs 0 → the row's actual percentage. The gap to 100% is the work left, drawn to scale.
      out.push(`<line x1="${x(0)}" y1="${y}" x2="${x(100)}" y2="${y}" stroke="var(--rule)" stroke-width="1.5" stroke-dasharray="2 4"/>`);
      out.push(`<line x1="${x(0)}" y1="${y}" x2="${x(r.pct)}" y2="${y}" stroke="${colour}" stroke-width="6" stroke-linecap="round" opacity="0.9"/>`);
      out.push(station(x(r.pct), y, colour, r.measured, r.measured));
      out.push(`<text x="${x(r.pct) + 13}" y="${y + 4}" class="pct">${r.pct}%</text>`);
      if (!r.measured) out.push(`<text x="${x(r.pct) + 46}" y="${y + 4}" class="sub">asserted</text>`);
    }
    y += 40;
  };

  pctLine("Zero-Trust thesis", "the five trust boundaries", LINES.thesis, thesis);
  pctLine("Build progress", "layers with a number", LINES.build, build);

  // --- Tracking registry: the 20 named workstreams (owner catch 2026-07-25 — the first cut dropped this
  // section entirely, so DSS.wasm / .spore / TritMesh simply vanished from the map). Grouped by state:
  // shipped = solid, building = hollow, post-v1 = hollow + dashed (declared out of the current horizon).
  if (meta.registry.length) {
    const groups = [["shipped", true, ""], ["building", false, ""], ["post-v1", false, ` stroke-dasharray="3 2.5"`]];
    out.push(`<text x="${PAD_L - 18}" y="${y}" text-anchor="end" class="line-name" fill="${LINES.build}">Tracking registry</text>`);
    out.push(`<text x="${PAD_L - 18}" y="${y + 14}" text-anchor="end" class="sub">${meta.registry.length} named workstreams</text>`);
    for (const [state, filled, dash] of groups) {
      const items = meta.registry.filter((r) => r.state === state);
      if (!items.length) continue;
      out.push(`<text x="${x(0)}" y="${y}" class="stn">${esc(state)} (${items.length})</text>`);
      y += 20;
      // Two columns so twenty rows do not double the map's height.
      items.forEach((r, i) => {
        const cx = x(0) + (i % 2) * ((TRACK / 2) | 0), cy = y + Math.floor(i / 2) * 20;
        out.push(`<circle cx="${cx}" cy="${cy}" r="5" fill="${filled ? LINES.build : "var(--paper)"}" stroke="${LINES.build}" stroke-width="2"${dash}/>`);
        out.push(`<text x="${cx + 12}" y="${cy + 4}" class="sub">${esc(r.item)}</text>`);
      });
      y += Math.ceil(items.length / 2) * 20 + 14;
    }
    y += 12;
  }

  // --- WORD rows: layers with no percentage at all. They belong on the map as terminus markers, because
  // omitting them would make the map look more complete than the project is.
  if (meta.wordRows.length) {
    out.push(`<text x="${PAD_L - 18}" y="${y}" text-anchor="end" class="line-name" fill="var(--ink)">Not a number</text>`);
    out.push(`<text x="${PAD_L - 18}" y="${y + 14}" text-anchor="end" class="sub">no percentage claimed</text>`);
    meta.wordRows.forEach((label, i) => {
      const ly = y + i * 22;
      out.push(`<circle cx="${x(0)}" cy="${ly}" r="5" fill="none" stroke="var(--ink)" stroke-width="2" stroke-dasharray="3 2.5"/>`);
      out.push(`<text x="${x(0) + 14}" y="${ly + 4}" class="stn">${esc(label)}</text>`);
    });
    y += meta.wordRows.length * 22 + 24;
  }

  const H = y + 76;
  const legend = [
    ["solid station", "reached / authority flipped"],
    ["hollow station", "not yet reached"],
    ["dashed ring", "the number is ASSERTED (hand-typed), not measured"],
  ].map(([k, v], i) => `<text x="${PAD_L}" y="${H - 54 + i * 15}" class="sub"><tspan class="stn">${esc(k)}</tspan> — ${esc(v)}</text>`).join("");

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="Galerina roadmap subway map">
<style>
  :root { --paper:#fbfaf7; --ink:#1b1a17; --rule:#c9c4ba; }
  @media (prefers-color-scheme: dark) { :root { --paper:#16181c; --ink:#e8e6e1; --rule:#3a3f47; } }
  svg { background: var(--paper); }
  text { font-family: ui-sans-serif, "Segoe UI", system-ui, sans-serif; fill: var(--ink); }
  .stn { font-size: 12.5px; font-weight: 600; }
  .sub { font-size: 10.5px; fill: var(--ink); opacity: .62; }
  .pct { font-size: 12px; font-weight: 700; font-variant-numeric: tabular-nums; }
  .line-name { font-size: 13.5px; font-weight: 700; letter-spacing: .02em; }
  .title { font-size: 19px; font-weight: 700; }
</style>
<rect width="100%" height="100%" fill="var(--paper)"/>
<text x="${PAD_L - 18}" y="34" text-anchor="end" class="title">Where the project is</text>
<text x="${PAD_L}" y="34" class="sub">${esc(meta.caption)}</text>
<text x="${PAD_L}" y="50" class="sub">${esc(meta.provenance)}</text>
${out.join("\n")}
${legend}
</svg>
`;
}

// --- the markdown block --------------------------------------------------------------------------------
// Deterministic: no clock. A timestamp would make every run drift and defeat the --check gate.
export function renderBlock(model) {
  const { stages, thesis, build, kernel, meta } = model;
  const flipped = stages.filter((s) => s.authoritative);
  const measured = [...thesis, ...build].filter((r) => r.measured).length;
  const total = thesis.length + build.length;
  const stageCell = (s) => `${s.authoritative ? "●" : "○"} ${s.name}`;
  return [
    BEGIN,
    `**${meta.caption}**`,
    ``,
    `![Galerina roadmap — subway map](build/component-health/roadmap-subway.svg)`,
    ``,
    `**Self-hosting line (RD-0528).** ${flipped.length} of ${stages.length} compiler stages are AUTHORITATIVE — the \`.fungi\` stage is the decider of record and the co-located \`.ts\` is retained as a running differential shadow. All ${stages.length} are byte-pinned in the stage-hash baseline.`,
    ``,
    `| stage | ${stages.map((s) => s.name).join(" | ")} |`,
    `|---|${stages.map(() => "---").join("|")}|`,
    `| authority | ${stages.map(stageCell).map((c) => c.split(" ")[0]).join(" | ")} |`,
    ``,
    `**Kernel cutover line (RD-0361).** ${kernel.length} sentinel twins are authoritative in the ledger. The differential remainder is not counted here — no ledger records a denominator, and inventing one would be a hand-typed number.`,
    ``,
    `| Zero-Trust boundary | % | evidence |`,
    `|---|--:|---|`,
    ...thesis.map((r) => `| ${r.label} | ${r.pct}% | ${r.measured ? "measured" : "**asserted**"} |`),
    ``,
    `| Build-progress layer | % | evidence |`,
    `|---|--:|---|`,
    ...build.map((r) => `| ${r.label} | ${r.pct}% | ${r.measured ? "measured" : "**asserted**"} |`),
    ...(meta.wordRows.length ? [``, `**No percentage claimed:** ${meta.wordRows.join(" · ")}.`] : []),
    ``,
    `**Tracking registry (${meta.registry.length}):** ` + ["shipped", "building", "post-v1"]
      .map((s) => `${s} ${meta.registry.filter((r) => r.state === s).length}`).join(" · ")
      + ` — every named workstream, from the same percent-audit source; the map's registry section lists each one.`,
    ``,
    `> **Read the map honestly: ${measured} of ${total} percentages are measured** (a live reading or a countable ladder); the remaining ${total - measured} are asserted — a considered judgement, but hand-typed. Burning that ratio down is itself tracked work, which is why the map draws the difference instead of hiding it.`,
    ``,
    `<sub>${meta.provenance} · regenerate: \`node scripts/gen-roadmap-subway.mjs --write\`</sub>`,
    END,
  ].join("\n");
}

// --- model assembly ------------------------------------------------------------------------------------
export function buildModel({ pa, hashBaseline, ledger, kernelLedger, version }) {
  const stages = stageLine(hashBaseline, ledger);
  const sect = (k) => pa.sections.find((s) => s.key === k) ?? { rows: [] };
  const num = (rows) => rows.filter((r) => typeof r.pct === "number")
    .map((r) => ({ label: r.label, pct: r.pct, measured: ["live", "ladder"].includes(evidenceClass(r)) }));
  const words = (rows) => rows.filter((r) => typeof r.pct !== "number").map((r) => r.label);
  const thesis = num(sect("zero-trust-thesis").rows);
  const build = num(sect("build-progress").rows);
  const kernel = kernelLedger?.twins ?? [];
  return {
    stages, thesis, build, kernel,
    meta: {
      caption: `v${version.version} · ${version.packageCount} packages · ${version.testCount} tests · ship-readiness ${pa.shipReadinessPct.toFixed(1)}% · Zero-Trust thesis avg ${pa.ztAvg}% · build avg ${pa.buildAvg}%`,
      provenance: "generated from component-health + the RD-0528/RD-0361 authority ledgers; exact build identity is in build/component-health/provenance.json",
      wordRows: [...words(sect("zero-trust-thesis").rows), ...words(sect("build-progress").rows)],
      // Every registry row, state normalised — the map must not drop a workstream (owner catch: v1 did).
      registry: sect("tracking-registry").rows.map((r) => ({ item: r.item, state: String(r.state) })),
    },
  };
}

function model() {
  return buildModel({
    pa: percentAudit(),
    hashBaseline: loadJSON(SOURCES.stageHashes),
    ledger: loadJSON(SOURCES.stageLedger),
    kernelLedger: loadJSON(SOURCES.kernelLedger),
    version: loadJSON(SOURCES.version),
  });
}

// One pure classifier for a target's state (R&D 0424, equivalence-proven 4/4 against the inline loop
// before adoption). Extracted so the ABSENCE path is drivable by the self-test — it was the one branch
// proven only by a one-off manual drive, which is not a repeatable proof.
export function classifyTarget(abs, block) {
  if (!existsSync(abs)) return "gone-missing";
  const text = readFileSync(abs, "utf8");
  const expected = injectBlock(text, block);
  if (expected === null) return "gone-unmarked";
  return text === expected ? "ok" : "stale";
}

const markerBounds = (text) => {
  const b = text.indexOf(BEGIN);
  const e = text.indexOf(END);
  if (
    b < 0
    || e < b
    || text.indexOf(BEGIN, b + BEGIN.length) >= 0
    || text.indexOf(END, e + END.length) >= 0
  ) return null;
  return { b, e };
};
const injectBlock = (text, block) => {
  const bounds = markerBounds(text);
  if (bounds === null) return null;
  const newline = text.includes("\r\n") ? "\r\n" : "\n";
  const localBlock = block.replace(/\r?\n/g, newline);
  return text.slice(0, bounds.b) + localBlock + text.slice(bounds.e + END.length);
};
const currentBlock = (text) => {
  const bounds = markerBounds(text);
  return bounds === null ? null : text.slice(bounds.b, bounds.e + END.length);
};

