  const throws = (fn) => { try { fn(); return false; } catch { return true; } };

  const hb = loadJSON(SOURCES.stageHashes), led = loadJSON(SOURCES.stageLedger);
  const stages = stageLine(hb, led);
  ok(stages.length === PIPELINE_ORDER.length, `stage line renders all ${PIPELINE_ORDER.length} stages`);
  ok(stages.some((s) => s.authoritative) && stages.every((s) => s.pinned), "at least one stage is flipped and every stage is byte-pinned (control: a blank ledger would fail this)");

